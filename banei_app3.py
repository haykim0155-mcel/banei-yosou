def parse_results_text_content(full_text):
    results = {}
    races = re.split(r"(\d{1,2}R\s+)", full_text)

    for i in range(1, len(races), 2):
        r_num = int(races[i].strip().replace("R", ""))
        block = races[i + 1]
        r_data = {
            "1着": None,
            "2着": None,
            "3着": None,
            "単勝": 0,
            "複勝1": 0,
            "複勝2": 0,
            "複勝3": 0,
            "枠連": 0,
            "馬連": 0,
            "馬単": 0,
            "ワイド1": 0,
            "ワイド2": 0,
            "ワイド3": 0,
            "3連複": 0,
            "3連単": 0,
        }

        top3 = []
        for line in block.split("\n"):
            m = re.match(r"^([123])\s+\d+\s+(\d{1,2})\s+", line.strip())
            if m:
                top3.append(int(m.group(2)))

        if len(top3) >= 1:
            r_data["1着"] = top3[0]
        if len(top3) >= 2:
            r_data["2着"] = top3[1]
        if len(top3) >= 3:
            r_data["3着"] = top3[2]

        def get_section(name, next_names):
            pattern = (
                re.escape(name)
                + r"\s+(.*?)(?=(?:"
                + "|".join(map(re.escape, next_names))
                + r"|\Z))"
            )
            m = re.search(pattern, block, re.DOTALL)
            return m.group(1) if m else ""

        p_tan = re.findall(
            r"([\d,]+)円",
            get_section(
                "単勝",
                [
                    "複勝",
                    "枠連",
                    "馬連",
                    "ワイド",
                    "馬単",
                    "3連複",
                    "3連単",
                    "▲ページTOPへ",
                ],
            ),
        )
        if p_tan:
            r_data["単勝"] = int(p_tan[0].replace(",", ""))

        p_fuku = re.findall(
            r"([\d,]+)円",
            get_section(
                "複勝",
                [
                    "枠連",
                    "馬連",
                    "ワイド",
                    "馬単",
                    "3連複",
                    "3連単",
                    "▲ページTOPへ",
                ],
            ),
        )
        for idx, p in enumerate(p_fuku[:3]):
            r_data[f"複勝{idx+1}"] = int(p.replace(",", ""))

        p_wakuren = re.findall(
            r"([\d,]+)円",
            get_section(
                "枠連",
                [
                    "馬連",
                    "ワイド",
                    "馬単",
                    "3連複",
                    "3連単",
                    "▲ページTOPへ",
                ],
            ),
        )
        if p_wakuren:
            r_data["枠連"] = int(p_wakuren[0].replace(",", ""))

        p_umaren = re.findall(
            r"([\d,]+)円",
            get_section(
                "馬連", ["ワイド", "馬単", "3連複", "3連単", "▲ページTOPへ"]
            ),
        )
        if p_umaren:
            r_data["馬連"] = int(p_umaren[0].replace(",", ""))

        p_umatan = re.findall(
            r"([\d,]+)円",
            get_section("馬単", ["3連複", "3連単", "▲ページTOPへ"]),
        )
        if p_umatan:
            r_data["馬単"] = int(p_umatan[0].replace(",", ""))

        p_wide = re.findall(
            r"([\d,]+)円",
            get_section(
                "ワイド", ["馬単", "3連複", "3連単", "▲ページTOPへ"]
            ),
        )
        for idx, p in enumerate(p_wide[:3]):
            r_data[f"ワイド{idx+1}"] = int(p.replace(",", ""))

        p_sanfuku = re.findall(
            r"([\d,]+)円",
            get_section("3連複", ["3連単", "▲ページTOPへ"]),
        )
        if p_sanfuku:
            r_data["3連複"] = int(p_sanfuku[0].replace(",", ""))

        p_santan = re.findall(
            r"([\d,]+)円", get_section("3連単", ["▲ページTOPへ"])
        )
        if p_santan:
            r_data["3連単"] = int(p_santan[0].replace(",", ""))

        results[f"{r_num}R"] = r_data

